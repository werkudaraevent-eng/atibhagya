const filename = fileURLToPath(import.meta.url)
const dirname = path.dirname(filename)

const serverURL = process.env.NEXT_PUBLIC_SERVER_URL || 'http://localhost:3000'

const databaseURI = process.env.DATABASE_URI || ''

/**
 * Production runs on Postgres (Payload Cloud or any managed instance). A
 * `file:` URI switches to SQLite so the CMS can be run locally without
 * standing up a database first — the schema is generated by Payload either
 * way, so the collections stay identical.
 */
/**
 * Object storage for uploads.
 *
 * Local disk is fine for development and for any host with a persistent
 * filesystem, but Vercel's is read-only and ephemeral — a photo uploaded there
 * disappears on the next deploy. Setting S3_BUCKET switches Payload over.
 *
 * The adapter speaks plain S3, so it also drives Cloudflare R2, DigitalOcean
 * Spaces, Wasabi, and Supabase Storage — anything with an S3 endpoint.
 */
const storage = process.env.S3_BUCKET
  ? [
      s3Storage({
        collections: { media: true },
        bucket: process.env.S3_BUCKET,
        config: {
          endpoint: process.env.S3_ENDPOINT,
          region: process.env.S3_REGION || 'auto',
          // Required by R2 and Supabase; harmless on AWS.
          forcePathStyle: process.env.S3_FORCE_PATH_STYLE !== 'false',
          credentials: {
            accessKeyId: process.env.S3_ACCESS_KEY_ID || '',
            secretAccessKey: process.env.S3_SECRET_ACCESS_KEY || '',
          },
        },
      }),
    ]
  : []

const db = databaseURI.startsWith('file:')
  ? sqliteAdapter({ client: { url: databaseURI } })
  : postgresAdapter({ pool: { connectionString: databaseURI } })

/** Where a document can be seen on the live site. */
const pathFor = (collection: string, slug: unknown, locale?: string) => {
  const prefix = locale === 'id' ? '/id' : ''
  if (collection === 'products') return `${prefix}/product/${slug}`
  if (collection === 'journeys') return `${prefix}/journey/${slug}`
  if (collection === 'about') return `${prefix}/about`
  if (collection === 'inquiry-form') return `${prefix}/inquiry`
  return prefix || '/'
}

export default buildConfig({
  serverURL,
  admin: {
    user: Users.slug,
    importMap: {
      baseDir: path.resolve(dirname),
    },
    meta: {
      titleSuffix: ' · Atibhagya',
      description: 'Atibhagya content management',
    },
    components: {
      graphics: {
        Logo: '@/admin/Graphics#Logo',
        Icon: '@/admin/Graphics#Icon',
      },
    },
    // A panel beside the form showing the real page, at three widths.
    livePreview: {
      breakpoints: [
        { name: 'mobile', label: 'Mobile', width: 390, height: 844 },
        { name: 'tablet', label: 'Tablet', width: 834, height: 1112 },
        { name: 'desktop', label: 'Desktop', width: 1440, height: 900 },
      ],
      collections: ['products', 'journeys'],
      globals: ['home', 'about', 'inquiry-form'],
      url: ({ data, collectionConfig, globalConfig, locale }) =>
        `${serverURL}${pathFor(
          collectionConfig?.slug ?? globalConfig?.slug ?? 'home',
          (data as { slug?: string })?.slug,
          typeof locale === 'string' ? locale : locale?.code,
        )}`,
    },
  },
  // The team works in Indonesian; English stays one click away in the account
  // menu for anyone who prefers it.
  i18n: {
    supportedLanguages: { en, id },
    fallbackLanguage: 'id',
  },
  collections: [
    ProductCategories,
    Products,
    Journeys,
    Venues,
    Facilitators,
    Inquiries,
    Media,
    Posts,
    Users,
  ],
  globals: [HomePage, AboutPage, InquiryFormCopy, SiteSettings],
  // URL strategy: `/` is English, `/id/…` is Indonesian.
  localization: {
    locales: [
      { label: 'English', code: 'en' },
      { label: 'Bahasa Indonesia', code: 'id' },
    ],
    defaultLocale: 'en',
    fallback: true,
  },
  editor: lexicalEditor(),
  secret: process.env.PAYLOAD_SECRET || '',
  typescript: {
    outputFile: path.resolve(dirname, 'payload-types.ts'),
  },
  db,
  // Without SMTP credentials Payload falls back to logging the email, so local
  // development works without a mail server.
  email: process.env.SMTP_HOST
    ? nodemailerAdapter({
        defaultFromAddress: process.env.SMTP_FROM || 'hello@atibhagya.com',
        defaultFromName: 'Atibhagya',
        transportOptions: {
          host: process.env.SMTP_HOST,
          port: Number(process.env.SMTP_PORT || 587),
          auth:
            process.env.SMTP_USER && process.env.SMTP_PASS
              ? { user: process.env.SMTP_USER, pass: process.env.SMTP_PASS }
              : undefined,
        },
      })
    : undefined,
  plugins: storage,
  cors: [serverURL],
  csrf: [serverURL],
  sharp,
})
