const filename = fileURLToPath(import.meta.url)
const dirname = path.dirname(filename)

const databaseURI = process.env.DATABASE_URI || ''

/**
 * Production runs on Postgres (Payload Cloud or any managed instance). A
 * `file:` URI switches to SQLite so the CMS can be run locally without
 * standing up a database first — the schema is generated by Payload either
 * way, so the collections stay identical.
 */
/**
 * Object storage for uploads.
 *
 * Local disk is fine for development and for any host with a persistent
 * filesystem, but Vercel's is read-only and ephemeral — a photo uploaded there
 * disappears on the next deploy. Setting S3_BUCKET switches Payload over.
 *
 * The adapter speaks plain S3, so it also drives Cloudflare R2, DigitalOcean
 * Spaces, Wasabi, and Supabase Storage — anything with an S3 endpoint.
 */
const storage = process.env.S3_BUCKET
  ? [
      s3Storage({
        collections: { media: true },
        bucket: process.env.S3_BUCKET,
        // The browser sends the file to R2 itself, by signed URL, instead of
        // through the server: Vercel caps a request body at 4.5 MB, which a
        // hero video would never fit.
        clientUploads: true,
        config: {
          endpoint: process.env.S3_ENDPOINT,
          region: process.env.S3_REGION || 'auto',
          // Required by R2 and Supabase; harmless on AWS.
          forcePathStyle: process.env.S3_FORCE_PATH_STYLE !== 'false',
          credentials: {
            accessKeyId: process.env.S3_ACCESS_KEY_ID || '',
            secretAccessKey: process.env.S3_SECRET_ACCESS_KEY || '',
          },
        },
      }),
    ]
  : []

/**
 * Two databases, two disciplines.
 *
 * Local work runs on SQLite with `push`: Payload reshapes the file to match
 * the config as it changes, asking in the terminal when data would be lost.
 * That is right for one developer and a throwaway file.
 *
 * Postgres — staging and production — never pushes. Every schema change is
 * a migration file under `src/migrations`, created with
 * `npm run migrate:create` against a Postgres database and committed, then
 * applied by `npm run migrate` as the first step of the production build.
 * A migration is reviewable, reversible and identical on staging and
 * production; a push is none of those.
 */
const db = databaseURI.startsWith('file:')
  ? sqliteAdapter({ client: { url: databaseURI } })
  : postgresAdapter({
      pool: { connectionString: databaseURI },
      push: false,
      migrationDir: path.resolve(dirname, 'migrations'),
    })

/**
 * Where the admin's preview panel should look.
 *
 * Products and journeys point at a staff-only route that reads the draft, so
 * an unpublished change shows up as soon as it is saved. Pages are globals;
 * their preview shows the published state until the change is published.
 */
const pathFor = (collection: string, slug: unknown, locale?: string) => {
  const prefix = locale === 'id' ? '/id' : ''
  if (collection === 'products') return `${prefix}/preview/product/${slug}`
  if (collection === 'journeys') return `${prefix}/preview/journey/${slug}`
  if (collection === 'about') return `${prefix}/preview/about`
  if (collection === 'inquiry-form') return `${prefix}/preview/inquiry`
  if (collection === 'catalogue') return `${prefix}/preview/catalogue`
  // A category shows itself as a filter on the listing.
  if (collection === 'product-categories') return `${prefix}/preview/catalogue`
  // Site settings are the footer and contact on every page; home stands in.
  return `${prefix}/preview/home`
}

